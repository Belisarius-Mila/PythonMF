    function libraryItemMeta(item) {
      const parts = [];
      if (item.read_state && item.read_state !== "normal") {
        parts.push(item.read_state_label || item.read_state);
      }
      const date = String(item.archived_at || "").slice(0, 10);
      if (date) parts.push(date);
      if (item.category_label) parts.push(item.category_label);
      if (item.category === "books" && item.book_author) parts.push(`Autor: ${item.book_author}`);
      if (item.category === "books" && item.book_isbn) parts.push(`ISBN: ${item.book_isbn}`);
      if (item.category === "books" && item.book_location) parts.push(`Umístění: ${item.book_location}`);
      if (item.source_label) parts.push(item.source_label);
      const url = item.canonical_url || item.source_url || "";
      if (url) {
        try {
          parts.push(new URL(url).hostname);
        } catch (_err) {
          parts.push(url);
        }
      }
      if (item.text_chars) parts.push(`${item.text_chars} znaků`);
      if (item.attachment_count) parts.push(`${item.attachment_count} příloh`);
      if (item.read_note) parts.push(item.read_note);
      return parts.join(" | ");
    }

    function libraryItemDetailMeta(item) {
      const lines = [];
      const summary = libraryItemMeta(item);
      if (summary) lines.push(summary);
      const tags = item && item.category === "books"
        ? libraryBookCategories(item)
        : (Array.isArray(item && item.tags) ? item.tags.filter(Boolean) : []);
      if (tags.length) lines.push(`${item && item.category === "books" ? "Kategorie" : "Tagy"}: ${tags.join(", ")}`);
      const sourceNote = String(item && item.source_note || "").trim();
      if (sourceNote) lines.push(`Poznámka ke zdroji: ${sourceNote}`);
      return lines.join("\n");
    }

