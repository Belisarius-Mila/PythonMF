    async function saveLibraryBook() {
      const title = libraryBookTitleInput.value.trim();
      const author = libraryBookAuthorInput.value.trim();
      const isbn = libraryBookIsbnInput.value.trim();
      const location = libraryBookLocationInput.value.trim();
      const summary = libraryBookSummaryInput.value.trim();
      if (!title || !author || !location || !summary) {
        libraryBookStatus.textContent = "Vyplň název, autora, umístění i stručný obsah knihy.";
        const missing = [
          [title, libraryBookTitleInput],
          [author, libraryBookAuthorInput],
          [location, libraryBookLocationInput],
          [summary, libraryBookSummaryInput],
        ].find(([value]) => !value);
        if (missing) missing[1].focus();
        return;
      }
      if (!confirmLibraryEditorDiscard()) return;
      closeLibraryEditor(true);
      const cover = validateSelectedLibraryBookCover(maxLibraryImageBytes);
      if (cover.error) {
        libraryBookStatus.textContent = cover.error;
        libraryBookCoverInput.focus();
        return;
      }
      libraryBookSaveBtn.disabled = true;
      libraryBookStatus.textContent = "Ukládám knihu do soukromé knihovny...";
      try {
        let preparedCover = null;
        if (cover.file) {
          libraryBookStatus.textContent = "Zmenšuji obálku před uložením knihy...";
          const originalCoverDataUrl = await blobToDataUrl(cover.file);
          const preparation = await postJson("/api/library/book/cover-prepare", {
            image_data_url: originalCoverDataUrl,
          });
          if (!preparation.ok || !preparation.image_data_url) {
            libraryBookStatus.textContent = preparation.message || "Obálku se nepodařilo bezpečně zmenšit.";
            return;
          }
          preparedCover = preparation;
          libraryBookStatus.textContent = "Obálka je zmenšená. Ukládám knihu do soukromé knihovny...";
        }
        const data = await postJson("/api/library/book", {
          title,
          author,
          isbn,
          location,
          summary,
          tags: selectedLibraryBookCategories(libraryBookCategoryChoices),
        });
        if (!data.ok) {
          libraryBookStatus.textContent = data.message || "Knihu se nepodařilo uložit.";
          return;
        }
        const item = data.item || {};
        let finalMessage = data.message || "Kniha byla uložena.";
        if (preparedCover && item.id) {
          try {
            const attachment = await postJson("/api/library/attachment/add", {
              article_id: item.id,
              image_data_url: preparedCover.image_data_url,
              filename: preparedCover.filename || "obalka-knihy.jpg",
              category: "books",
              label: "Obálka knihy",
              role: "book_cover",
              tags: "obalka",
              note: "",
            });
            finalMessage += attachment.ok
              ? " Obálka byla připojena."
              : ` Obálku se nepodařilo připojit: ${attachment.message || "neznámá chyba"}. Přidej ji v části Přílohy.`;
          } catch (coverError) {
            recordFrontendError(coverError);
            finalMessage += ` Obálku se nepodařilo připojit: ${coverError}. Přidej ji v části Přílohy.`;
          }
        } else if (preparedCover) {
          finalMessage += " Obálku se nepodařilo připojit, protože odpověď neobsahovala identifikátor nové karty. Přidej ji v části Přílohy.";
        }
        libraryBookStatus.textContent = finalMessage;
        libraryBookTitleInput.value = "";
        libraryBookAuthorInput.value = "";
        libraryBookIsbnInput.value = "";
        libraryBookLocationInput.value = "";
        setLibraryBookSelectedCategories(libraryBookCategoryChoices, []);
        libraryBookSourceInput.value = "";
        libraryBookSummaryInput.value = "";
        clearLibraryBookIsbnLookupResult();
        libraryBookIsbnLookupStatus.textContent = "Po stisku se do veřejného katalogu odešle pouze validované ISBN. Výsledek se neuloží automaticky. Když se nic nenajde, knihu můžeš normálně uložit ručně.";
        clearLibraryBookCover();
        clearLibraryBookOcrPhotos();
        setLibraryAddMode("");
        await loadLibraryCategory("books");
        if (item.id) await loadLibraryItem(item.id);
        libraryStatus.textContent = finalMessage;
      } catch (err) {
        recordFrontendError(err);
        libraryBookStatus.textContent = `Chyba uložení knihy: ${err}`;
      } finally {
        libraryBookSaveBtn.disabled = false;
      }
    }

